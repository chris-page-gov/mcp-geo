#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from scripts.agent_control_common import (  # noqa: E402
    DEFAULT_ACTIVE_MODE_MANIFEST_PATH,
    DEFAULT_OUTPUT_ROOT,
    build_control_vault,
    utc_now,
)
from scripts.obsidian_cli import (  # noqa: E402
    DEFAULT_OBSIDIAN_APP,
    DEFAULT_OBSIDIAN_USER_DATA,
    preflight,
)

ROOT_FILES = (
    "AGENTS.md",
    "CLAUDE.md",
    "GEMINI.md",
    ".github/copilot-instructions.md",
    "CONTEXT.md",
    "PROGRESS.MD",
)

CONTROL_HOME = "Obsidian/MCP Geo Agent Control/00 Home/00 - Agent Home.md"
CONTROL_FOCUS = "Obsidian/MCP Geo Agent Control/10 State/Current Focus.md"
CONTROL_QUEUE = "Obsidian/MCP Geo Agent Control/10 State/Work Queue.md"
CONTROL_VERIFY = "Obsidian/MCP Geo Agent Control/10 State/Verification.md"
CONTROL_REPO_MAP = "Obsidian/MCP Geo Agent Control/20 Generated/Repo Map Digest.md"
CONTROL_RELEASE = "Obsidian/MCP Geo Agent Control/20 Generated/Release Summary.md"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Switch the repo agent-control mode.")
    parser.add_argument(
        "--mode",
        choices=["classic", "obsidian"],
        required=True,
        help="Agent-control mode to apply.",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=DEFAULT_OUTPUT_ROOT,
        help="Agent control vault root.",
    )
    parser.add_argument(
        "--mode-manifest",
        type=Path,
        default=DEFAULT_ACTIVE_MODE_MANIFEST_PATH,
        help="Machine-readable active-mode manifest path.",
    )
    parser.add_argument(
        "--app-path",
        type=Path,
        default=DEFAULT_OBSIDIAN_APP,
        help="Obsidian app bundle path used for CLI preflight.",
    )
    parser.add_argument(
        "--cli-path",
        type=Path,
        default=None,
        help="Explicit Obsidian CLI binary path override.",
    )
    parser.add_argument(
        "--user-data-path",
        type=Path,
        default=DEFAULT_OBSIDIAN_USER_DATA,
        help="Obsidian user-data directory used to detect updated runtime packages.",
    )
    parser.add_argument(
        "--require-cli",
        action="store_true",
        help="Fail the switch if the Obsidian CLI preflight is not ready.",
    )
    return parser


def git_stdout(repo_root: Path, *args: str) -> str:
    completed = subprocess.run(
        ["git", *args],
        cwd=repo_root,
        check=True,
        capture_output=True,
        text=True,
    )
    return completed.stdout


def read_head_file(repo_root: Path, rel_path: str) -> str:
    return git_stdout(repo_root, "show", f"HEAD:{rel_path}")


def head_commit(repo_root: Path) -> str:
    return git_stdout(repo_root, "rev-parse", "HEAD").strip()


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def cli_status_line(cli_preflight: dict[str, Any]) -> str:
    if cli_preflight.get("ready"):
        return "- Obsidian CLI preflight: `ready`."
    issues = cli_preflight.get("issues", [])
    if not issues:
        return "- Obsidian CLI preflight: `unknown`."
    first = issues[0]
    return f"- Obsidian CLI preflight: `{first['code']}` ({first['message']})"


def render_obsidian_agents(cli_preflight: dict[str, Any]) -> str:
    return "\n".join(
        [
            "# MCP Geo Agent Control",
            "",
            "This repository is currently in `obsidian` agent-control mode.",
            "This file is generated by `python3 scripts/switch_agent_mode.py --mode obsidian`.",
            "",
            "## Read Order",
            f"1. `{CONTROL_HOME}`",
            f"2. `{CONTROL_FOCUS}`",
            f"3. `{CONTROL_QUEUE}`",
            f"4. `{CONTROL_VERIFY}`",
            f"5. `{CONTROL_REPO_MAP}`",
            "",
            "## Defaults",
            "- Do not default to reading `CHANGELOG.md`; use the generated release digest instead.",
            f"- Preferred release summary: `{CONTROL_RELEASE}`",
            "- Use `python3 scripts/validate_agent_control.py` to verify vault and CLI readiness.",
            cli_status_line(cli_preflight),
            "",
        ]
    )


