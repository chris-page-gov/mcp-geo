def write_obsidian_mode(repo_root: Path, cli_preflight: dict[str, Any]) -> None:
    rendered = {
        "AGENTS.md": render_obsidian_agents(cli_preflight),
        "CLAUDE.md": render_obsidian_claude(),
        "GEMINI.md": render_obsidian_gemini(),
        ".github/copilot-instructions.md": render_obsidian_copilot(),
        "CONTEXT.md": render_context_shim(cli_preflight),
        "PROGRESS.MD": render_progress_shim(cli_preflight),
    }
    for rel_path, content in rendered.items():
        write_text(repo_root / rel_path, content)


def restore_classic_mode(repo_root: Path) -> None:
    for rel_path in ROOT_FILES:
        write_text(repo_root / rel_path, read_head_file(repo_root, rel_path))


def write_mode_manifest(
    manifest_path: Path,
    *,
    mode: str,
    cli_preflight: dict[str, Any] | None,
    repo_root: Path,
) -> dict[str, Any]:
    payload = {
        "mode": mode,
        "updated_at": utc_now(),
        "head_commit": head_commit(repo_root),
        "control_vault_root": str(repo_root / "Obsidian" / "MCP Geo Agent Control"),
        "root_files": list(ROOT_FILES),
        "default_read_order": [
            CONTROL_HOME,
            CONTROL_FOCUS,
            CONTROL_QUEUE,
            CONTROL_VERIFY,
            CONTROL_REPO_MAP,
        ],
        "cli_preflight": cli_preflight,
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return payload


def switch_mode(
    repo_root: Path,
    *,
    mode: str,
    output_root: Path,
    mode_manifest_path: Path,
    app_path: Path,
    user_data_path: Path,
    cli_path: Path | None,
    require_cli: bool,
) -> dict[str, Any]:
    control_manifest_path = repo_root / "data" / "agent_control" / "control_vault_manifest.json"
    build_control_vault(
        repo_root,
        output_root=output_root,
        manifest_path=control_manifest_path,
    )
    cli_preflight = preflight(
        output_root,
        app_path=app_path,
        user_data_path=user_data_path,
        cli_path=cli_path,
    )
    if mode == "obsidian":
        if require_cli and not cli_preflight.get("ready"):
            first = cli_preflight["issues"][0]
            raise ValueError(f"{first['code']}: {first['message']}")
        write_obsidian_mode(repo_root, cli_preflight)
    else:
        restore_classic_mode(repo_root)
    return write_mode_manifest(
        mode_manifest_path,
        mode=mode,
        cli_preflight=cli_preflight,
        repo_root=repo_root,
    )


def main() -> int:
    args = build_parser().parse_args()
    manifest = switch_mode(
        REPO_ROOT,
        mode=args.mode,
        output_root=args.output_root,
        mode_manifest_path=args.mode_manifest,
        app_path=args.app_path,
        user_data_path=args.user_data_path,
        cli_path=args.cli_path,
        require_cli=args.require_cli,
    )
    print(f"Switched agent mode to {manifest['mode']}")
    print(f"Mode manifest: {args.mode_manifest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
